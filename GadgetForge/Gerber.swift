import Foundation

// MARK: - Gerber RS-274X + Excellon writers
// Units: mm. Coordinate format 4.6 (FSLAX46Y46).

private struct GW {
    var s = ""
    mutating func line(_ t: String) { s += t + "\n" }
    func c(_ v: Double) -> String { String(Int((v * 1_000_000).rounded())) }
    mutating func move(_ x: Double, _ y: Double) { line("X\(c(x))Y\(c(y))D02*") }
    mutating func draw(_ x: Double, _ y: Double) { line("X\(c(x))Y\(c(y))D01*") }
    mutating func flash(_ x: Double, _ y: Double) { line("X\(c(x))Y\(c(y))D03*") }
    mutating func aperture(_ n: Int) { line("D\(n)*") }
    mutating func header(_ what: String) {
        line("G04 \(what) - generated by GadgetForge*")
        line("%FSLAX46Y46*%")
        line("%MOMM*%")
    }
    mutating func footer() { line("M02*") }
    mutating func rect(_ x0: Double, _ y0: Double, _ x1: Double, _ y1: Double) {
        move(x0, y0); draw(x1, y0); draw(x1, y1); draw(x0, y1); draw(x0, y0)
    }
}

enum Gerber {
    static let traceWidth = 0.35
    static let viaPad = 0.8
    static let viaDrill = 0.3

    static func topCopper(_ b: PCBBoard) -> String {
        var g = GW()
        g.header("Top copper")
        g.line("%ADD10C,\(traceWidth)*%")   // traces
        g.line("%ADD11R,1.800X1.800*%")     // SMD pads
        g.line("%ADD12C,\(viaPad)*%")       // via annular rings
        g.aperture(10)
        for t in b.traces where t.layer == 0 {
            guard let first = t.points.first else { continue }
            g.move(first.0, first.1)
            for p in t.points.dropFirst() { g.draw(p.0, p.1) }
        }
        g.aperture(11)
        for f in b.footprints { for p in f.pads { g.flash(p.cx, p.cy) } }
        g.aperture(12)
        for v in b.vias { g.flash(v.x, v.y) }
        g.footer()
        return g.s
    }

    static func bottomCopper(_ b: PCBBoard) -> String {
        var g = GW()
        g.header("Bottom copper")
        g.line("%ADD10C,\(traceWidth)*%")
        g.line("%ADD12C,\(viaPad)*%")
        g.aperture(10)
        for t in b.traces where t.layer == 1 {
            guard let first = t.points.first else { continue }
            g.move(first.0, first.1)
            for p in t.points.dropFirst() { g.draw(p.0, p.1) }
        }
        g.aperture(12)
        for v in b.vias { g.flash(v.x, v.y) }
        g.footer()
        return g.s
    }

    static func topSilk(_ b: PCBBoard) -> String {
        var g = GW()
        g.header("Top silkscreen")
        g.line("%ADD13C,0.150*%")
        g.aperture(13)
        for f in b.footprints {
            g.rect(f.x, f.y, f.x + f.w, f.y + f.d)
            // pin-1 marker
            if let p = f.pads.first {
                g.move(p.cx - 1.2, p.cy); g.draw(p.cx + 1.2, p.cy)
            }
        }
        g.footer()
        return g.s
    }

    static func outline(_ b: PCBBoard) -> String {
        var g = GW()
        g.header("Board outline")
        g.line("%ADD14C,0.100*%")
        g.aperture(14)
        g.rect(0, 0, b.width, b.height)
        g.footer()
        return g.s
    }

    /// Excellon drill file: T1 = via drills, T2 = mounting holes.
    static func drills(_ b: PCBBoard) -> String {
        var s = ""
        s += "M48\n"
        s += ";DRILL file generated by GadgetForge\n"
        s += "METRIC,TZ\n"
        s += "T1C\(String(format: "%.3f", viaDrill))\n"
        s += "T2C3.200\n"
        s += "%\n"
        s += "T1\n"
        for v in b.vias {
            s += String(format: "X%.3fY%.3f\n", v.x, v.y)
        }
        s += "T2\n"
        for (hx, hy) in [(4.0, 4.0), (b.width - 4.0, 4.0), (4.0, b.height - 4.0), (b.width - 4.0, b.height - 4.0)] {
            s += String(format: "X%.3fY%.3f\n", hx, hy)
        }
        s += "M30\n"
        return s
    }
}
